'use strict';

/**
 * Local server config: port probing, token, and persisting runtime info.
 *
 * Runtime info is written to ~/.workgremlin/server.json and shared by the Electron main
 * process, the renderer, and the reporter CLI. The token is generated on the first start and
 * then reused on every later start (see persistedToken), so a remote client does not lose
 * access every time the server restarts.
 */

const fs = require('node:fs');
const net = require('node:net');
const crypto = require('node:crypto');
const { DEFAULTS, DEMO_PROJECT_ID, home } = require('@workgremlin/shared');
// WorkGremlin's own storage locations + logic-free file helpers come from shared/paths.js
// (single source of truth). config.js keeps only the behavior: token / port / file permissions.
const {
  ensureHome,
  serverInfoPath,
  dbPath: defaultDbPath,
  isPidAlive,
  readServerInfo: readServerInfoFile,
} = require('@workgremlin/shared/paths');

/**
 * Id of the virtual demo project.
 *
 * Demo mode is an in-memory, read-only session/project pair (see demo/provider.js); no row with
 * this id is written to the office tables. The underscores are deliberate: real project ids are
 * generated by slug() in project.js and only contain [a-z0-9-], so the two can never collide.
 *
 * This identity is fixed. `WORKGREMLIN_PROJECT` belongs to reporter attribution only; letting it
 * rename the demo project would make the virtual id and the display slug disagree.
 */
const DEMO_PROJECT = DEMO_PROJECT_ID;

/** Display name of the demo project (shown side by side with real projects in the UI) */
const DEMO_PROJECT_NAME = '演示工程';

function newToken() {
  return crypto.randomBytes(24).toString('hex');
}

/**
 * Token persisted by a previous run, or null when this is the first start.
 *
 * Read **without** the liveness check: the old process may be gone, but the token in
 * server.json is still the one remote clients were given, so a restart must keep it.
 * `--no-token` writes an empty token, which is deliberately not reused: a later normal start
 * should generate a real one.
 *
 * @returns {string|null}
 */
function persistedToken() {
  try {
    const info = JSON.parse(fs.readFileSync(serverInfoPath(), 'utf8'));
    return info && typeof info.token === 'string' && info.token ? info.token : null;
  } catch {
    return null;
  }
}

/**
 * @param {number} port
 * @param {string} [host] interface the port will actually be bound to (defaults to loopback)
 */
function isPortFree(port, host = '127.0.0.1') {
  return new Promise((resolve) => {
    const srv = net.createServer();
    srv.once('error', () => resolve(false));
    srv.once('listening', () => srv.close(() => resolve(true)));
    // Probe the same interface the server will bind: 0.0.0.0 can collide with a port that is
    // only taken on another interface, which a 127.0.0.1 probe would not see.
    srv.listen(port, host);
  });
}

/**
 * Find the first available port within [start, end].
 * @param {number} [start]
 * @param {number} [end]
 * @param {string} [host]
 * @returns {Promise<number|null>}
 */
async function pickPort(start = DEFAULTS.PORT_START, end = DEFAULTS.PORT_END, host = '127.0.0.1') {
  for (let port = start; port <= end; port += 1) {
    // eslint-disable-next-line no-await-in-loop
    if (await isPortFree(port, host)) return port;
  }
  return null;
}

/**
 * @param {{port: number, token: string, pid: number, dbPath: string, startedAt: number,
 *          version?: string, previousPid?: number|null, project?: string, projectName?: string,
 *          workspacePath?: string}} info
 */
function writeServerInfo(info) {
  ensureHome();
  const file = serverInfoPath();
  fs.writeFileSync(file, JSON.stringify(info, null, 2), { mode: 0o600 });
  try {
    fs.chmodSync(file, 0o600);
  } catch {
    /* ignore */
  }
  return file;
}

/** @returns {Record<string, any>|null} */
function readServerInfo() {
  // Server-side reader: a server.json left behind by a crashed run must not be treated as valid.
  return readServerInfoFile({ requireAlive: true });
}

/**
 * Keep only the token after a normal shutdown.
 *
 * Runtime fields (port / pid) are deliberately removed: readers that need a reachable server
 * must treat this file as absent, while the next start can still reuse the token. This is what
 * lets remote clients survive a restart without a separate token file.
 *
 * @param {string} token
 */
function writeStoppedInfo(token) {
  ensureHome();
  const file = serverInfoPath();
  fs.writeFileSync(file, JSON.stringify({ token, stoppedAt: Date.now() }, null, 2), { mode: 0o600 });
  try {
    fs.chmodSync(file, 0o600);
  } catch {
    /* ignore on non-POSIX systems */
  }
  return file;
}

module.exports = {
  home,
  ensureHome,
  serverInfoPath,
  defaultDbPath,
  DEMO_PROJECT,
  DEMO_PROJECT_NAME,
  newToken,
  persistedToken,
  isPortFree,
  isPidAlive,
  pickPort,
  writeServerInfo,
  readServerInfo,
  writeStoppedInfo,
};
