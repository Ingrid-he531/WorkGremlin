'use strict';

/**
 * Local server config: port probing, token, and persisting runtime info.
 *
 * Runtime info is written to ~/.workgremlin/server.json and shared by the Electron main
 * process, the renderer, and the reporter CLI. It listens on 127.0.0.1 only; a random token
 * is generated on every start to stop other local processes from forging reports.
 */

const fs = require('node:fs');
const net = require('node:net');
const crypto = require('node:crypto');
const { DEFAULTS, DEMO_PROJECT_ID, home } = require('@workgremlin/shared');
// WorkGremlin's own storage locations + logic-free file helpers come from shared/paths.js
// (single source of truth). config.js keeps only the behavior: token / port / file permissions.
const {
  ensureHome,
  serverInfoPath,
  dbPath: defaultDbPath,
  isPidAlive,
  readServerInfo: readServerInfoFile,
} = require('@workgremlin/shared/paths');

/**
 * Id of the virtual demo project.
 *
 * Demo mode is an in-memory, read-only session/project pair (see demo/provider.js); no row with
 * this id is written to the office tables. The underscores are deliberate: real project ids are
 * generated by slug() in project.js and only contain [a-z0-9-], so the two can never collide.
 *
 * This identity is fixed. `WORKGREMLIN_PROJECT` belongs to reporter attribution only; letting it
 * rename the demo project would make the virtual id and the display slug disagree.
 */
const DEMO_PROJECT = DEMO_PROJECT_ID;

/** Display name of the demo project (shown side by side with real projects in the UI) */
const DEMO_PROJECT_NAME = '演示工程';

function newToken() {
  return crypto.randomBytes(24).toString('hex');
}

/** @param {number} port */
function isPortFree(port) {
  return new Promise((resolve) => {
    const srv = net.createServer();
    srv.once('error', () => resolve(false));
    srv.once('listening', () => srv.close(() => resolve(true)));
    srv.listen(port, '127.0.0.1');
  });
}

/**
 * Find the first available port within [start, end].
 * @param {number} [start]
 * @param {number} [end]
 * @returns {Promise<number|null>}
 */
async function pickPort(start = DEFAULTS.PORT_START, end = DEFAULTS.PORT_END) {
  for (let port = start; port <= end; port += 1) {
    // eslint-disable-next-line no-await-in-loop
    if (await isPortFree(port)) return port;
  }
  return null;
}

/**
 * @param {{port: number, token: string, pid: number, dbPath: string, startedAt: number,
 *          version?: string, previousPid?: number|null, project?: string, projectName?: string,
 *          workspacePath?: string}} info
 */
function writeServerInfo(info) {
  ensureHome();
  const file = serverInfoPath();
  fs.writeFileSync(file, JSON.stringify(info, null, 2), { mode: 0o600 });
  try {
    fs.chmodSync(file, 0o600);
  } catch {
    /* ignore */
  }
  return file;
}

/** @returns {Record<string, any>|null} */
function readServerInfo() {
  // Server-side reader: a server.json left behind by a crashed run must not be treated as valid.
  return readServerInfoFile({ requireAlive: true });
}

function clearServerInfo() {
  const file = serverInfoPath();
  if (fs.existsSync(file)) {
    try {
      fs.unlinkSync(file);
    } catch {
      /* ignore */
    }
  }
}

module.exports = {
  home,
  ensureHome,
  serverInfoPath,
  defaultDbPath,
  DEMO_PROJECT,
  DEMO_PROJECT_NAME,
  newToken,
  isPortFree,
  isPidAlive,
  pickPort,
  writeServerInfo,
  readServerInfo,
  clearServerInfo,
};
