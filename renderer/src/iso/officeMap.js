const dist = (a, b) => Math.hypot(a.x - b.x, a.y - b.y);

function nearestNode(pt) {
  let best = null;
  let bestD = Infinity;
  for (const [k, v] of Object.entries(N)) {
    const d = dist(pt, v);
    if (d < bestD) {
      bestD = d;
      best = k;
    }
  }
  return best;
}

function bfs(from, to) {
  if (from === to) return [from];
  const prev = new Map([[from, null]]);
  const q = [from];
  while (q.length) {
    const cur = q.shift();
    for (const nb of ADJ.get(cur) || []) {
      if (prev.has(nb)) continue;
      prev.set(nb, cur);
      if (nb === to) {
        const path = [nb];
        let c = cur;
        while (c) {
          path.unshift(c);
          c = prev.get(c);
        }
        return path;
      }
      q.push(nb);
    }
  }
  return null;
}

/**
 * 规划路径：从任意点走到任意点，返回途经点数组（含精确起终点）。
 * 先吸附到最近的路网节点走 BFS，再补上首尾真实坐标，避免瞬移。
 */
export function route(from, to) {
  const a = nearestNode(from);
  const b = nearestNode(to);
  const path = bfs(a, b) || [];
  const pts = path.map((k) => ({ ...N[k] }));
  if (pts.length) {
    if (dist(pts[0], from) > 0.05) pts.unshift({ ...from });
    else pts[0] = { ...from };
    const last = pts[pts.length - 1];
    if (dist(last, to) > 0.05) pts.push({ ...to });
    else pts[pts.length - 1] = { ...to };
  } else {
    pts.push({ ...from }, { ...to });
  }
  return pts;
}
