const ADJ = (() => {
  const m = new Map();
  Object.keys(N).forEach((k) => m.set(k, []));
  EDGES.forEach(([a, b]) => {
    if (!m.has(a) || !m.has(b)) return;
    m.get(a).push(b);
    m.get(b).push(a);
  });
  return m;
})();

