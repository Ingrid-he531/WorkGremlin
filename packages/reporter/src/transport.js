'use strict';

/**
 * Loopback HTTP(S) client shared by the reporter entry points (SDK / hook forwarder).
 *
 * Why this is not plain `fetch`:
 *   · The server may run with TLS (`--tls`, `server.tls` in config.json). `server.json` then carries
 *     `protocol: "https"`, but a plain `http://` request to that port is answered with **nothing at
 *     all** ("Empty reply from server", measured 2026-10-30). The hook must never block an agent,
 *     so it swallowed the failure silently: every hook-based floor (4F Claude Code, 3F Codex,
 *     1F / 5F / 6F …) stopped writing task records the moment TLS was turned on, while polling
 *     floors (8F OpenCode) kept working because they never go through the hook.
 *   · `fetch` has no per-request way to accept the server's self-signed certificate. `https.request`
 *     with `rejectUnauthorized: false` scopes the exception to this one loopback request, whereas
 *     `NODE_TLS_REJECT_UNAUTHORIZED=0` would disable verification for the whole agent process.
 *
 * The response shape intentionally mirrors the small part of `fetch` the reporters use
 * (`ok` / `status` / `json()` / `text`), so call sites stay unchanged.
 */

const http = require('node:http');
const https = require('node:https');

/**
 * Loopback base URL for a `server.json` record. The scheme has to follow what the server bound —
 * host + port alone cannot tell a client whether the listener speaks http or https.
 * @param {{port: number, protocol?: string}} info
 * @returns {string}
 */
function baseUrl(info) {
  const scheme = String((info && info.protocol) || '').toLowerCase() === 'https' ? 'https' : 'http';
  return `${scheme}://127.0.0.1:${info.port}`;
}

/**
 * Minimal fetch-shaped request.
 * @param {string} url absolute URL
 * @param {{method?: string, headers?: Record<string,string>, body?: string|null, timeoutMs?: number}} [init]
 * @returns {Promise<{ok: boolean, status: number, text: string, json: () => Promise<any>}>}
 */
function request(url, init = {}) {
  const { method = 'GET', headers = {}, body = null, timeoutMs = 5_000 } = init;
  return new Promise((resolve, reject) => {
    let target;
    try {
      target = new URL(url);
    } catch (err) {
      reject(err);
      return;
    }
    const secure = target.protocol === 'https:';
    const payload = body == null ? null : typeof body === 'string' ? body : JSON.stringify(body);
    const opts = {
      method,
      hostname: target.hostname,
      port: target.port || (secure ? 443 : 80),
      path: `${target.pathname}${target.search}`,
      headers: { ...headers },
      // The certificate is generated by the server itself for loopback use; the CA store can never
      // vouch for it. Scoped to this request only — never a process-wide TLS switch.
      rejectUnauthorized: false,
    };
    if (payload != null && !Object.keys(opts.headers).some((h) => h.toLowerCase() === 'content-length')) {
      opts.headers['content-length'] = Buffer.byteLength(payload);
    }
    const req = (secure ? https : http).request(opts, (res) => {
      const chunks = [];
      res.on('data', (chunk) => chunks.push(chunk));
      res.on('end', () => {
        const text = Buffer.concat(chunks).toString('utf8');
        resolve({
          ok: res.statusCode >= 200 && res.statusCode < 300,
          status: res.statusCode || 0,
          text,
          json: () => {
            try {
              return Promise.resolve(JSON.parse(text));
            } catch (err) {
              return Promise.reject(err);
            }
          },
        });
      });
    });
    // A hung socket must not keep an agent hook waiting: the CLI awaits the hook synchronously.
    req.setTimeout(timeoutMs, () => req.destroy(new Error(`timeout after ${timeoutMs}ms`)));
    req.on('error', reject);
    if (payload != null) req.write(payload);
    req.end();
  });
}

module.exports = { baseUrl, request };
